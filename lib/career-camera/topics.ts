export const determineProfile = (profession: Profession): ProfileKey =>
  TVP_PROFESSIONS.has(profession.name) ? "TVP" : "RKBP";

export const getRecommendedTopics = (
  profession: Profession,
  data: TopicsData = topicsData,
) => {
  const profile = determineProfile(profession);
  const profileData = data.profiles[profile];
  const allTopics = [
    ...profileData.topics.red,
    ...profileData.topics.green,
    ...profileData.topics.blue,
    ...profileData.topics.orange,
  ];
  const keywords = professionKeywords[profession.name] ?? ["программирование", "разработка", "система"];

  const topics = allTopics
    .map((topic) => {
      let score = 0;
      const title = topic.title.toLowerCase();
      keywords.forEach((keyword) => {
        if (title.includes(keyword.toLowerCase())) score += 10;
      });
      if (IT_PROFESSIONS_FOR_TOPICS.has(profession.name)) {
        if (profileData.topics.green.includes(topic) || profileData.topics.blue.includes(topic)) score += 5;
      }
      if (TVP_PROFESSIONS.has(profession.name)) {
        if (profileData.topics.orange.includes(topic)) score += 10;
        if (profileData.topics.blue.includes(topic)) score += 5;
      }
      if (["Предприниматель", "Маркетолог"].includes(profession.name)) {
        if (profileData.topics.orange.includes(topic)) score += 5;
      }
      return { topic, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 8)
    .map((item) => item.topic);

  return { topics, profile: profileData };
};

export const parseHours = (value: string): number => {
  if (!value) return 0;
  const match = value.match(/(\d+)\s*час/);
  return match ? Number.parseInt(match[1], 10) : 0;
};

export const formatCourse = (course: string[]): string => {
  if (!course.length) return "";
  if (course.length === 1) return `${course[0]} курс`;
  return `${course[0]}–${course[course.length - 1]} курс`;
};
